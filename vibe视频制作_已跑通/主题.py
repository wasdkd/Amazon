# #### 模块 A：暧昧期与“上头”机制（最容易爆流量、吸粉极快）
# 1. **《为什么对方越冷淡，你反而越上头？》**
#    * **17s 锚词**：`间歇强化`
#    * **画面隐喻**：斯金纳箱对比——恒定给糖的平直曲线（无感）vs 随机掉落奖励的尖刺多巴胺曲线（剧烈成瘾）。
# 2. **《为什么第一眼心动，其实是大脑骗了你？》**
#    * **17s 锚词**：`吊桥效应`
#    * **画面隐喻**：两条心率波（紧张刺激波 vs 好感波）在晃动的桥面上交叉重叠，大脑错把蓝色恐惧波标成了粉色心动。
# 3. **《为什么我们总会被“若即若离”的人拿捏？》**
#    * **17s 锚词**：`未完结效应`（或 `蔡格尼克效应`）
#    * **画面隐喻**：闭合的圆环安静熄灭；缺了一块的残缺圆环却一直在屏幕中心高频闪烁、持续耗电。
# 4. **《为什么越容易追到的人，反而越不被珍惜？》**
#    * **17s 锚词**：`稀缺溢价`
#    * **画面隐喻**：供给密度条拉满时价值指针跌到底部；设置门槛与留白后，心理估值曲线陡峭拉升。
# 5. **《为什么喜欢一个人，看 Ta 连缺点都像优点？》**
#    * **17s 锚词**：`光环效应`
#    * **画面隐喻**：一颗核心强光球体瞬间扩散，把周围原本标灰色的“小毛病节点”全部染成温暖滤镜色。
